"""OLAP query runner (`spec 03` section 6, `07` section 5).

Runs every file in `sql/olap/`, reads the `-- param:` defaults from each header, accepts
`--param name=value` overrides, and writes one CSV per query under
`reports/results/olap/`.

An empty result is not an error: queries 08 and 09 depend on artefacts from later phases
(regimes in Phase 3, signals in Phase 6) and legitimately return nothing before then.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Mapping

import pandas as pd
from sqlalchemy import Engine

from src.common.config import ConfigError, load_config
from src.common.db import get_engine, read_sql
from src.common.log import get_logger

#: Exit codes (`07` section 5).
EXIT_OK = 0
EXIT_ERROR = 1
EXIT_DATA_FAILURE = 2

#: SQL directory, resolved from the package location.
OLAP_DIR = Path(__file__).resolve().parents[2] / "sql" / "olap"

#: `-- param: name = value` in a file header.
PARAM_RE = re.compile(r"^--\s*param:\s*(\w+)\s*=\s*(.*)$", re.IGNORECASE)


def parse_params(sql: str) -> dict[str, Any]:
    """Read the `-- param: name = value` defaults from a query header.

    Args:
        sql: Full text of a `.sql` file.

    Returns:
        Mapping of declared parameter names to their default values, cast to int or
        float where the text looks numeric.
    """
    params: dict[str, Any] = {}
    for line in sql.splitlines():
        match = PARAM_RE.match(line.strip())
        if match:
            params[match.group(1)] = _cast(match.group(2).strip())
    return params


def _cast(value: str) -> Any:
    """Cast a numeric string to int or float; leave everything else as text."""
    text_value = value.strip().strip("'\"")
    if not text_value:
        return ""
    try:
        return int(text_value)
    except ValueError:
        pass
    try:
        return float(text_value)
    except ValueError:
        return text_value


def parse_overrides(pairs: list[str]) -> dict[str, Any]:
    """Turn `--param name=value` strings into a typed mapping."""
    overrides: dict[str, Any] = {}
    for pair in pairs:
        if "=" not in pair:
            raise ValueError(f"--param expects name=value, got {pair!r}")
        name, _, value = pair.partition("=")
        overrides[name.strip()] = _cast(value)
    return overrides


def build_pivot_sql(years: list[int]) -> str:
    """Regenerate query 06 with one column per year from `olap.pivot_years`.

    Args:
        years: Years to pivot on.

    Returns:
        The full SQL statement. Falls back to a single column when no years are given.
    """
    columns = ",\n       ".join(
        f"ROUND(AVG(CASE WHEN d.year = {int(year)} THEN i.return_1d END) * 100, 3) AS y{int(year)}"
        for year in years
    )
    return f"""-- operation: PIVOT (sectors as rows, years as columns)
-- generated by src.olap.run.build_pivot_sql from olap.pivot_years
SELECT s.sector,
       {columns}
FROM fact_indicator i
JOIN dim_date  d ON d.date_key  = i.date_key
JOIN dim_stock s ON s.stock_key = i.stock_key
WHERE s.instrument_type = 'EQUITY'
GROUP BY s.sector
ORDER BY s.sector;"""


def _named_params_used(sql: str) -> set[str]:
    """Names bound as `:name` in the statement, ignoring the `::` cast syntax."""
    return set(re.findall(r"(?<![:\w]):(\w+)", sql))


def _latest_year(engine: Engine) -> int | None:
    row = read_sql(engine, "SELECT MAX(year) AS y FROM dim_date WHERE is_trading_day = 1")
    value = row["y"].iloc[0] if not row.empty else None
    return int(value) if value is not None and pd.notna(value) else None


def _latest_date(engine: Engine) -> str | None:
    row = read_sql(
        engine,
        "SELECT MAX(full_date) AS d FROM dim_date WHERE is_trading_day = 1",
    )
    value = row["d"].iloc[0] if not row.empty else None
    return str(value) if value is not None and pd.notna(value) else None


def run_query(
    engine: Engine,
    path: Path,
    overrides: Mapping[str, Any],
    cfg: Mapping[str, Any],
    out_dir: Path,
) -> pd.DataFrame:
    """Run one OLAP file and write its result.

    Args:
        engine: Warehouse engine.
        path: The `.sql` file.
        overrides: `--param` values.
        cfg: Loaded config.
        out_dir: Folder for the result CSV.

    Returns:
        The result DataFrame, possibly empty.
    """
    log = get_logger(__name__)
    file_text = path.read_text(encoding="utf-8")

    # Query 06 is a template: its year columns come from config, so the statement is
    # regenerated rather than used verbatim.
    sql_text = (
        build_pivot_sql([int(y) for y in cfg["olap"]["pivot_years"]])
        if path.stem.startswith("06_")
        else file_text
    )

    # Defaults come from the file header, which is correct for both branches: the
    # generated pivot SQL declares no parameters.
    params: dict[str, Any] = {**parse_params(file_text), **overrides}

    # A data-dependent default with no rows falls back to the latest available value.
    if "year" in params and "year" not in overrides:
        available = _latest_year(engine)
        if available is not None:
            params["year"] = available
    if "as_of_date" in params and "as_of_date" not in overrides:
        latest = _latest_date(engine)
        if latest is not None:
            params["as_of_date"] = latest

    # Only pass the parameters the statement actually binds.
    used = _named_params_used(sql_text)
    bound = {name: value for name, value in params.items() if name in used}

    df = read_sql(engine, sql_text, bound)

    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / f"{path.stem}.csv", index=False)

    if df.empty:
        log.warning("%s returned no rows (expected before later phases run)", path.stem)
    else:
        log.info("%s -> %d row(s) written to %s", path.stem, len(df), out_dir / f"{path.stem}.csv")
    return df


def run(
    cfg: dict[str, Any],
    *,
    all_queries: bool,
    stem: str | None,
    params: list[str],
    pivot_years: list[int] | None,
) -> int:
    """Run the requested queries and return an exit code."""
    log = get_logger(__name__)
    engine = get_engine(cfg)

    if pivot_years:
        cfg["olap"]["pivot_years"] = [int(y) for y in pivot_years]

    overrides = parse_overrides(params)
    if OLAP_DIR is not None and not OLAP_DIR.exists():
        log.error("OLAP directory not found: %s", OLAP_DIR)
        return EXIT_DATA_FAILURE

    files = sorted(OLAP_DIR.glob("*.sql"))
    if stem:
        files = [f for f in files if f.stem.startswith(stem)]
        if not files:
            log.error("no OLAP query matches %r", stem)
            return EXIT_DATA_FAILURE

    out_dir = Path(cfg["paths"]["results"]) / "olap"
    failures = 0
    for path in files:
        try:
            run_query(engine, path, overrides, cfg, out_dir)
        except Exception as exc:  # noqa: BLE001 - one bad query must not stop the rest
            log.error("%s failed: %s", path.stem, exc)
            failures += 1

    log.info("ran %d quer(y/ies), %d failure(s)", len(files), failures)
    return EXIT_OK if failures == 0 else EXIT_ERROR


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m src.olap.run",
        description="Run the OLAP queries in sql/olap and write CSV results.",
    )
    parser.add_argument("--all", action="store_true", help="Run every query.")
    parser.add_argument("--query", default=None, help="Run queries whose stem starts with this.")
    parser.add_argument(
        "--param",
        action="append",
        default=[],
        metavar="NAME=VALUE",
        help="Override a query parameter. Repeatable.",
    )
    parser.add_argument(
        "--pivot-years",
        default=None,
        help="Comma-separated years for query 06, overriding olap.pivot_years.",
    )
    parser.add_argument("--config", default=None, help="Override config file.")
    return parser


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns 0 on success, 1 unexpected, 2 data failure."""
    args = _build_parser().parse_args(argv)
    try:
        cfg = load_config(args.config)
    except ConfigError as exc:
        print(f"config error: {exc}", file=sys.stderr)
        return EXIT_ERROR

    years = [int(y) for y in args.pivot_years.split(",") if y.strip()] if args.pivot_years else None
    try:
        return run(
            cfg,
            all_queries=args.all or not args.query,
            stem=args.query,
            params=args.param,
            pivot_years=years,
        )
    except ValueError as exc:
        print(f"bad argument: {exc}", file=sys.stderr)
        return EXIT_ERROR
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return EXIT_ERROR
    except Exception as exc:  # noqa: BLE001 - the CLI must not traceback at the user
        get_logger(__name__).exception("olap run failed")
        print(f"unexpected error: {exc}", file=sys.stderr)
        return EXIT_ERROR


if __name__ == "__main__":
    raise SystemExit(main())
